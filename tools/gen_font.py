#!/usr/bin/env python3
"""Bake assets/fonts/Fontm6x11.png (m6x11 by Daniel Linssen, free with
attribution) into src/game/font_gen.odin: one 14-row bitmap per ASCII glyph
32..126 plus its advance (ink width + 1). Needs Pillow. Run from the repo root."""
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
im = Image.open(os.path.join(ROOT, "assets", "fonts", "Fontm6x11.png")).convert("L")
CW, CH = 10, 14
rows_out, adv = [], []
for code in range(32, 127):
    i = code - 32
    sx, sy = (i % 16) * CW, (i // 16) * CH
    rows = []
    maxx = -1
    for y in range(CH):
        bits = 0
        for x in range(CW):
            if im.getpixel((sx + x, sy + y)) < 128:
                bits |= 1 << x
                maxx = max(maxx, x)
        rows.append(bits)
    rows_out.append(rows)
    adv.append(maxx + 2 if maxx >= 0 else 5)  # space: 5 px
L = ["// GENERATED by tools/gen_font.py from assets/fonts/Fontm6x11.png",
     "// (m6x11 by Daniel Linssen, managore.itch.io, free with attribution). Do not edit.",
     "package game", "", "FONT_H :: 14", "FONT_BASE :: 11", "",
     "FONT_ROWS := [95][14]u16{"]
for r in rows_out:
    L.append("\t{%s}," % ", ".join(str(b) for b in r))
L.append("}")
L.append("")
L.append("FONT_ADV := [95]u8{%s}" % ", ".join(str(a) for a in adv))
L.append("")
open(os.path.join(ROOT, "src", "game", "font_gen.odin"), "w").write("\n".join(L))
print("wrote src/game/font_gen.odin; advance of 'a' =", adv[ord('a') - 32], "'0' =", adv[ord('0') - 32], "'M' =", adv[ord('M') - 32])
